package main

import (
	"bytes"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

const cliDocPath = "docs/api/cli.md"

func newGenerateDocsCommand(root *cobra.Command) *cobra.Command {
	return &cobra.Command{
		Use:    "__generate-docs [output]",
		Hidden: true,
		Args:   cobra.MaximumNArgs(1),
		RunE: func(_ *cobra.Command, args []string) error {
			path := cliDocPath
			if len(args) == 1 {
				path = args[0]
			}
			return os.WriteFile(path, renderCLIDoc(root), 0o644)
		},
	}
}

func renderCLIDoc(root *cobra.Command) []byte {
	root.InitDefaultCompletionCmd()
	var out bytes.Buffer
	fmt.Fprintln(&out, "<!-- Code generated by ./scripts/generate-docs.sh; DO NOT EDIT. -->")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "# CLI reference")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "This page is generated from the Cobra command tree returned by "+
		"`newRootCommand` in [`cmd/khora`](../../cmd/khora). Regenerate it with:")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "```sh")
	fmt.Fprintln(&out, "./scripts/generate-docs.sh")
	fmt.Fprintln(&out, "```")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "Check it for staleness with `./scripts/check-generated.sh`.")

	writeCommandDoc(&out, root, true)
	var walk func(*cobra.Command)
	walk = func(parent *cobra.Command) {
		children := append([]*cobra.Command(nil), parent.Commands()...)
		sort.Slice(children, func(i, j int) bool { return children[i].Name() < children[j].Name() })
		for _, cmd := range children {
			if !cmd.IsAvailableCommand() || cmd.Hidden {
				continue
			}
			writeCommandDoc(&out, cmd, false)
			walk(cmd)
		}
	}
	walk(root)
	return out.Bytes()
}

func writeCommandDoc(out *bytes.Buffer, cmd *cobra.Command, root bool) {
	flags := commandFlags(cmd, root)
	fmt.Fprintf(out, "\n## `%s`\n\n", cmd.CommandPath())
	description := strings.TrimSpace(cmd.Long)
	if description == "" {
		description = strings.TrimSpace(cmd.Short)
	}
	if description != "" {
		fmt.Fprintln(out, description)
		fmt.Fprintln(out)
	}
	fmt.Fprintln(out, "```text")
	fmt.Fprintln(out, commandUsage(cmd, len(flags) > 0))
	fmt.Fprintln(out, "```")

	if len(cmd.Aliases) > 0 {
		fmt.Fprintf(out, "\nAliases: `%s`\n", strings.Join(cmd.Aliases, "`, `"))
	}

	if len(flags) == 0 {
		return
	}
	fmt.Fprintln(out, "\n| Option | Default | Description |")
	fmt.Fprintln(out, "| --- | --- | --- |")
	for _, f := range flags {
		name := "--" + f.Name
		if f.Shorthand != "" {
			name = "-" + f.Shorthand + ", " + name
		}
		fmt.Fprintf(out, "| `%s` | `%s` | %s |\n", name, markdownCell(flagDefault(f)), markdownCell(f.Usage))
	}
}

func commandUsage(cmd *cobra.Command, hasFlags bool) string {
	use := cmd.CommandPath()
	if _, suffix, ok := strings.Cut(cmd.Use, " "); ok {
		use += " " + suffix
	}
	if hasFlags && !cmd.DisableFlagsInUseLine && !strings.Contains(use, "[flags]") {
		use += " [flags]"
	}
	return use
}

func commandFlags(cmd *cobra.Command, root bool) []*pflag.Flag {
	if root {
		cmd.InitDefaultVersionFlag()
	}
	var flags []*pflag.Flag
	cmd.LocalNonPersistentFlags().VisitAll(func(f *pflag.Flag) {
		if !f.Hidden && f.Name != "help" {
			flags = append(flags, f)
		}
	})
	cmd.PersistentFlags().VisitAll(func(f *pflag.Flag) {
		if !f.Hidden && f.Name != "help" {
			flags = append(flags, f)
		}
	})
	sort.Slice(flags, func(i, j int) bool { return flags[i].Name < flags[j].Name })
	return flags
}

func flagDefault(f *pflag.Flag) string {
	if f.DefValue == "" {
		return `""`
	}
	return f.DefValue
}

func markdownCell(s string) string {
	s = strings.ReplaceAll(s, "\\", `\\`)
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}
