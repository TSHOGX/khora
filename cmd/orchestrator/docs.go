package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strings"
)

const orchestratorDocPath = "docs/configuration/orchestrator.md"

func runOrchestratorDocGenerator(args []string) bool {
	if len(args) == 0 || args[0] != "__generate-docs" {
		return false
	}
	if len(args) > 2 {
		fmt.Fprintln(os.Stderr, "orchestrator: __generate-docs accepts at most one output path")
		os.Exit(2)
	}
	path := orchestratorDocPath
	if len(args) == 2 {
		path = args[1]
	}
	if err := os.WriteFile(path, renderOrchestratorDoc(), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "orchestrator: generate docs: %v\n", err)
		os.Exit(1)
	}
	return true
}

func renderOrchestratorDoc() []byte {
	var values orchestratorFlags
	fs := newOrchestratorFlagSet("orchestrator", flag.ContinueOnError, &values)

	var out bytes.Buffer
	fmt.Fprintln(&out, "<!-- Code generated by ./scripts/generate-docs.sh; DO NOT EDIT. -->")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "# Orchestrator configuration")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "The orchestrator reads configuration from command-line flags. This page is generated "+
		"from `newOrchestratorFlagSet` in [`cmd/orchestrator/flags.go`](../../cmd/orchestrator/flags.go). Regenerate it with:")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "```sh")
	fmt.Fprintln(&out, "./scripts/generate-docs.sh")
	fmt.Fprintln(&out, "```")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "Check it for staleness with `./scripts/check-generated.sh`.")
	fmt.Fprintln(&out)
	fmt.Fprintln(&out, "| Flag | Default | Description |")
	fmt.Fprintln(&out, "| --- | --- | --- |")
	fs.VisitAll(func(f *flag.Flag) {
		fmt.Fprintf(&out, "| `--%s` | `%s` | %s |\n", f.Name, markdownFlagCell(orchestratorFlagDefault(f)), markdownFlagCell(f.Usage))
	})
	return out.Bytes()
}

func orchestratorFlagDefault(f *flag.Flag) string {
	if f.DefValue == "" {
		return `""`
	}
	return f.DefValue
}

func markdownFlagCell(s string) string {
	s = strings.ReplaceAll(s, "\\", `\\`)
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}
