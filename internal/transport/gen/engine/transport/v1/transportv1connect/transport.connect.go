func NewFsServiceHandler(svc FsServiceHandler, opts ...connect.HandlerOption) (string, http.Handler) {
	fsServiceReadHandler := connect.NewUnaryHandler(
		FsServiceReadProcedure,
		svc.Read,
		connect.WithSchema(fsServiceReadMethodDescriptor),
		connect.WithHandlerOptions(opts...),
	)
	fsServiceWriteHandler := connect.NewUnaryHandler(
		FsServiceWriteProcedure,
		svc.Write,
		connect.WithSchema(fsServiceWriteMethodDescriptor),
		connect.WithHandlerOptions(opts...),
	)
	return "/engine.transport.v1.FsService/", http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch r.URL.Path {
		case FsServiceReadProcedure:
			fsServiceReadHandler.ServeHTTP(w, r)
		case FsServiceWriteProcedure:
			fsServiceWriteHandler.ServeHTTP(w, r)
		default:
			http.NotFound(w, r)
		}
	})
}

