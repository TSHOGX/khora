#!/usr/bin/env bash
# Record a substrate acceptance run against the SHA it ran on.
#
# The README's headline claim is that the engine is "verified against the real
# substrate". That claim is only checkable if a run is written down WITH THE COMMIT
# IT RAN ON: the previous record carried an exit code and package list but no SHA,
# so nothing could tell that it predated M10 and M11 entirely, and it rotted into a
# false claim while looking like evidence.
#
# The record is TRACKED (docs/substrate-runs/), for two reasons that turned out to be
# the same reason. An untracked file is one nothing can keep honest — the old record
# was gitignored — and `scripts/check-substrate-coverage.sh` has to READ the record
# in a fresh CI checkout, which it cannot do if the file is not in the tree.
#
# It is MARKDOWN, and that is a constraint rather than a preference:
# `test/preflight/substrategate` classifies only `.md` as inert. A `.log` record
# would make the commit that records a run itself require a substrate run to certify
# it — a gate that can never be satisfied, since certifying that commit needs another
# commit of the same kind. See ADR-0005.
#
# Usage:
#   scripts/record-substrate-run.sh            # all three tiers (what a release needs)
#   scripts/record-substrate-run.sh --quick    # the routine substrate tier only
#
# The run happens against the WORKING TREE, and the SHA is read at the start and
# re-checked at the end: a commit landing mid-run would make the record name a tree
# that was never tested.
set -uo pipefail

cd "$(git rev-parse --show-toplevel)" || exit 2

quick=0
[[ "${1:-}" == "--quick" ]] && quick=1

SHA="$(git rev-parse HEAD)"
if [[ -n "$(git status --porcelain)" ]]; then
  echo "record-substrate-run: FAIL — the working tree is dirty."
  echo "  The record names a SHA, so it must describe a tree that SHA actually is."
  echo "  Commit or stash first, then run this."
  exit 2
fi

OUT="docs/substrate-runs/${SHA:0:12}.md"
mkdir -p docs/substrate-runs
raw="$(mktemp)"
trap 'rm -f "$raw"' EXIT

# `-p 1` is not tuning: these packages launch real runsc containers, and running them
# concurrently starves the in-guest health probes the reaper's idle logic reads.
run_tier() {
  local name="$1"; shift
  echo "=== $name ===" | tee -a "$raw"
  # -v so the record carries per-test results; a package-level `ok` cannot be counted
  # and cannot show which tests skipped.
  sudo env "PATH=$PATH" "HOME=$HOME" go test -v "$@" 2>&1 | tee -a "$raw"
  # PIPESTATUS[0], not $?: $? is tee's status, which is 0 even when the suite fails.
  # This is the bug that left the old record claiming EXIT=0.
  local rc="${PIPESTATUS[0]}"
  echo "EXIT[$name]=$rc" | tee -a "$raw"
  return "$rc"
}

rc_total=0
run_tier substrate -tags substrate -count=1 -p 1 ./... || rc_total=1
if (( ! quick )); then
  run_tier drainrace -tags 'substrate,drainrace' -count=1 -p 1 -run 'TestPauseDrain' ./test/ || rc_total=1
  run_tier quotachurn -tags 'substrate,quotachurn' -count=1 -p 1 ./internal/btrfs || rc_total=1
fi

SHA_AFTER="$(git rev-parse HEAD)"
if [[ "$SHA" != "$SHA_AFTER" ]]; then
  echo "record-substrate-run: FAIL — HEAD moved during the run ($SHA -> $SHA_AFTER)."
  echo "  The record would name a tree that was never tested. Re-run on a still HEAD."
  exit 2
fi

# Counted from the `--- PASS/SKIP/FAIL:` lines `go test -v` emits, with -o so
# subtests (which are indented) count too. Subtests ARE tests here: the acceptance
# suite uses table subtests heavily, and counting only top-level funcs undercounts
# what actually ran. `|| true` because grep exits 1 on no match, which is a real
# answer (zero) rather than an error.
count() { grep -coE "^[[:space:]]*--- $1:" "$raw" || true; }
ok="$(count PASS)"
skipped="$(count SKIP)"
failed="$(count FAIL)"
ran=$(( ok + skipped + failed ))

{
  echo "# Substrate run — \`${SHA:0:12}\`"
  echo
  echo "Generated by \`scripts/record-substrate-run.sh\`. Do not hand-edit: the point of"
  echo "this file is that it is the output of a run, not an assertion about one."
  echo
  echo "| field | value |"
  echo "| --- | --- |"
  echo "| commit | \`$SHA\` |"
  echo "| date | $(date -u +%Y-%m-%dT%H:%M:%SZ) |"
  echo "| host | $(uname -srm) |"
  echo "| go | $(go version | cut -d' ' -f3) |"
  echo "| runsc | $(runsc --version 2>/dev/null | head -1 || echo 'not on PATH') |"
  if (( quick )); then
    echo "| tags | \`substrate\` (--quick: drainrace and quotachurn NOT run) |"
  else
    echo "| tags | \`substrate\`, \`substrate,drainrace\`, \`substrate,quotachurn\` |"
  fi
  echo "| exit | $rc_total |"
  echo "| tests run | $ran |"
  echo "| passed | $ok |"
  echo "| skipped | $skipped |"
  echo "| failed | $failed |"
  echo
  if (( quick )); then
    echo "**Partial: \`--quick\`.** The drainrace and quotachurn tiers were not run, so this"
    echo "record does not cover the §4.2 pause/write race or btrfs quota-row reclamation."
    echo
  fi
  echo "A handful of skips is expected — read the reasons below, not the count. Anything"
  echo "that FAILS is a finding."
  echo
  echo '```'
  # The full transcript, so a reader can check the counts above rather than trust them.
  cat "$raw"
  echo '```'
} > "$OUT"

echo
echo "record-substrate-run: wrote $OUT (exit=$rc_total, run=$ran pass=$ok skip=$skipped fail=$failed)"
if (( rc_total != 0 )); then
  echo "record-substrate-run: the run FAILED — the record says so. Fix the finding; do not tag."
fi
exit "$rc_total"
